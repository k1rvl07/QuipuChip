#pragma once

#include <stddef.h>
#include <stdint.h>

#include "config.h"

namespace pm {
namespace vault {

// Ошибки хранилища. BootStrap — раздел есть, но записи ещё нет; WrongPassword —
// GCM не подтвердил ключ; Tampered — заголовок/структура нарушены; Budget —
// превышен жёсткий байтовый бюджет; NoSpace — не помещается новая запись.
enum class VaultError {
  Ok = 0,
  NotFound = 1,
  BootStrap = 2,
  WrongPassword = 3,
  Tampered = 4,
  Budget = 5,
  NoSpace = 6,
  Serial = 7,
  Crypto = 8,
  Io = 9,
  TooManyEntries = 10,
  EntryTooLong = 11,
};

const char* toString(VaultError e);

// Сериализованная запись должна укладываться в config::kMaxEntryLen (1024 Б)
// вместе с id. Сумма фиксированных полей ниже — 896 Б, что оставляет 124 Б на
// id и заголовок записи; предыдущая раскладка (64+128+256+256+512 = 1216 Б) в
// лимит не помещалась в принципе, поэтому запись нельзя было бы сохранить ни
// разу, даже не нарушая правила.
struct Entry {
  uint32_t id;
  char title[48];
  char login[96];
  char password[160];
  char url[192];
  char note[400];
};

// Размер записи на диске без учёта id/len/nonce/tag.
constexpr size_t kEntryPayloadMax = sizeof(Entry) - sizeof(uint32_t);

struct Stats {
  uint32_t entryCount;
  size_t liveBytes;
  size_t usedBytes;
  uint32_t generation;
  bool compactedOnce;
};

// Открывает/создаёт хранилище. При создании генерируются соли, устройство
// инициализируется. Возвращает BootStrap, если записи ещё нет.
// Вторым аргументом deviceKey раньше передавался материал device-фактора, но
// он не использовался: ключ выводится внутри, из соли в самом слоте заголовка.
VaultError begin(const char* password);

// Загружает живые записи в память. Требует успешного begin().
// Записей может быть меньше maxCount, если буфер мал; фактическое число — в
// outCount. Счётчики байтов при этом не меняются.
VaultError load(Entry* out, uint32_t maxCount, uint32_t* outCount);

// Создаёт или обновляет запись. e.id == 0 — новая запись с присвоенным id,
// иначе обновление существующей. Проверяет три инварианта: счётчик, длина
// записи, жёсткий байтовый бюджет живых данных.
VaultError add(const Entry& e, uint32_t* outId);

// Удаляет запись надгробной записью. Физически данные уходят при компакции.
VaultError remove(uint32_t id);

// Стирает хранилище и заводит пустое заново под тем же паролем с новыми солями.
VaultError clear(const char* password);

// Полное уничтожение без пароля и без открытой сессии. Единственная операция,
// которая работает на заблокированном хранилище, — и именно поэтому она нужна
// для сброса: забытый пароль не мешает уничтожить данные, их нечем открыть.
// Раздел стирается целиком, после чего устройство читается как Unprovisioned и
// требует нового provisioning. Обратимо это только новым provisioning'ом с
// другим паролем, но прежние записи восстановить нечем.
VaultError reset();

const Stats& stats();

// Разовые счётчики и признак открытости. Однопоточные, без мьютекса: g_ready и
// g_live — выровненные 32-битные поля, поэтому читатель не увидит половину
// значения, но может увидеть пару полей из разных моментов времени.
//
// Мьютекс здесь намеренно НЕ берётся: при неверном пароле begin() держит его
// все ~2.9 с PBKDF2, и count() в HTTP-обработчике висел бы на всё это время.
// Слой авторизации читает состояние через snapshot(), а эти два вызова оставлены
// для selftest и диагностики в однопоточном контексте.
uint32_t count();
bool initialized();

// Закрывает сессию: wipe ключа, заголовка, солей и индексов. Флеш не трогается —
// close() ничего не стирает на разделе, он лишь выбрасывает материал из RAM.
// После него initialized() == false, а count() == 0, хотя хранилище на флеше
// цело и открывается заново тем же паролем.
//
// close() обязателен перед следующим begin(): без него старая сессия осталась
// бы в памяти, и ответ на новый пароль пришёл бы из прежнего открытого
// хранилища, а не из заголовков.
void close();

// Состояние хранилища для слоя авторизации.
enum class State {
  Unprovisioned = 0,  // раздел пуст, пароль ещё не задан
  Locked = 1,         // хранилище есть, но не открыто
  Unlocked = 2,       // открыто этой сессией
};

const char* toString(State s);

// Разовая инициализация до создания задач. Обязательна, иначе HTTP-сервер на
// первый вопрос о состоянии получит от provisioned() false на заполненном
// устройстве: до неё никто раздел vault не открывал, и указатель на раздел ещё
// не найден. UI показал бы «устройство не настроено» и предложил бы первичную
// настройку поверх существующих данных.
//
// initialize() ничего не открывает и пароля не требует: только создаёт мьютекс,
// ищет раздел и читает признак provisioned с флеша, публикуя его в snapshot().
// Дёшево, блокировок не создаёт, вызывается один раз из setup().
void initialize();

// Снимок состояния. Снимок, а не вызовы count()/initialized() по отдельности:
// HTTP-обработчик читает его БЕЗ мьютекса, потому что блокировка на время
// разблокировки (PBKDF2 ~2.9 с) означала бы зависший на всё это время сервер.
// Снимок пишется под мьютексом в критической секции и читается тоже в ней, так
// что читатель всегда видит целый набор полей, а не их смесь.
struct Snapshot {
  State state;
  uint32_t entryCount;
  uint32_t generation;
  size_t liveBytes;
};

// Текущий снимок состояния. Потокобезопасен, блокировки не берёт.
Snapshot snapshot();

// Есть ли на разделе хранилище. Определяет, показывать ли пользователю
// provisioning, или ждать пароль. Работает без пароля: читает только магию и
// флаг provisioned из слотов заголовков.
//
// Ограничение, о котором надо помнить: флаг provisioned входит в обнуляемую
// при AAD часть заголовка, поэтому до пароля его нечем аутентифицировать.
// Тот, кто может писать во флеш, в состоянии снять флаг с обоих слотов — и
// begin() на такой раздел заведёт новое хранилище, стерев прежнее. Это свойство
// появилось вместе с форматом PMV1, close() и provisioned() его не ухудшают:
// без флага раздел всё равно читается как пустой.
//
// Работает и до initialize(), и до первого begin(): раздел ищется сам. Истина,
// если флаг есть в ЛЮБОМ из двух слотов, чтобы оборванная запись свежего слота
// не выглядела как «устройство не настроено».
//
// Возвращает «есть ли записи, о которых известно устройству», а не «можно ли их
// прочитать»: подделка флага в дампе флеша меняет лишь то, какое меню увидит
// UI, но не расшифровывает ничего. Для решения «показать ли поле ввода пароля»
// этой точности хватает; для решения «есть ли данные» — нет.
bool provisioned();

// Читает одну запись по id, без распаковки всего журнала. Требует открытого
// хранилища; для отсутствующего id — NotFound.
VaultError get(uint32_t id, Entry* out);

}  // namespace vault
}  // namespace pm
