#pragma once

#include <stddef.h>
#include <stdint.h>

#include "config.h"
#include "vault.h"

// Слой авторизации: provisioning, разблокировка, сессия, блокировка по неудачам.
//
// Модуль ничего не знает про HTTP. Работа с паролем уходит в отдельную задачу
// по трём причинам, и все три обязательны:
//
//  1. PBKDF2 держит CPU ~2.9 с на слот, а begin() осматривает оба слота
//     безусловно, то есть разблокировка стоит ~5.8 с. Воркер на равном с httpd
//     приоритете не отдал бы ядро серверу, и polling-эндпоинт не ответил бы —
//     асинхронная модель 202 + опрос перестала бы работать.
//  2. vault::begin() удерживает мьютекс vault все эти 5.8 с. Любой HTTP-обработчик,
//     который полез бы в vault::count(), встал бы на всё время.
//  3. Считать PBKDF2 в контексте задачи httpd нельзя ещё и потому, что стек
//     httpd занят буфером раздачи на kHttpChunkBytes.
//
// Модуль не делает HTTP-запросов сам: пароль наружу отдаётся через poll(), и
// обязан быть забран РОВНО ОДИН РАЗ — второй poll() вернёт пустую строку.
namespace pm {
namespace auth {

// Что заказать воркеру. Порядок не важен, значения попадают в лог.
enum class Job : uint8_t {
  Provision = 0,  // создать хранилище и выдать сгенерированный пароль
  Unlock = 1,     // открыть существующее хранилище введённым паролем
  Reset = 2,      // уничтожить хранилище без пароля, для забытого мастер-пароля
};

// Итог операции. Pending и Busy — не ошибки, а состояния, отличать которые
// обязан HTTP-слой: первое означает «опроси позже», второе «занято, повтори».
enum class Result : uint8_t {
  Pending = 0,
  Ok = 1,
  WrongPassword = 2,
  Refused = 3,   // provisioning поверх уже provisioned-хранилища
  Lockout = 4,   // временная блокировка после серии неудач
  Busy = 5,      // очередь занята
  Error = 6,     // сбой хранилища или криптографии
};

const char* toString(Result r);

// Снимок состояния для GET /api/auth/state. Читается без блокировок: поля
// обновляются воркером, а ответ собирается под короткой критической секцией.
struct State {
  bool provisioned;      // на флеше есть заголовок с флагом provisioned
  bool unlocked;         // хранилище открыто этой сессией
  bool busy;             // воркер занят
  uint8_t failCount;     // неудачных попыток подряд, для показа в UI
  uint32_t lockoutMsLeft;  // осталось ждать до конца блокировки
};

// Длина токена сессии в виде, в котором он ходит по проводу: 32 байта в hex.
constexpr size_t kSessionTokenHexLen = config::kSessionTokenLen * 2;

// Вид job'а для poll(). password заполняется ТОЛЬКО для Provision и только пока
// результат Ok и пароль ещё не забран; после этого поле обнуляется.
//
// sessionToken заполняется для Provision и Unlock при результате Ok и тоже ровно
// один раз. Без него протокол нерабочий: клиент, разблокировавший хранилище,
// не знал бы токен новой сессии, потому что токен живёт только в памяти модуля и
// GET /api/auth/session требует его заголовком. Выдавать его иначе нечем — сам
// токен не восстановим из пароля.
struct JobView {
  Job kind;
  Result result;
  char password[config::kMasterPasswordChars + 1];
  char sessionToken[kSessionTokenHexLen + 1];
};

// Идентификатор job'а.
//
// Случайные 64 бита, а не счётчик. Идентификатор — единственный секрет,
// защищающий /api/auth/job/{id} до появления сессии: под этим маршрутом отдаётся
// одноразовый мастер-пароль provisioning'а и токен новой сессии. Со счётчиком
// подбор сводился бы к последовательным запросам job/1, job/2, ... любой
// процесс на хосте забрал бы пароль, а HTTP-слой это не может закрыть: до
// разблокировки заголовка X-PM-Session ещё нет, а пароль никому не пушится.
//
// 0 зарезервирован под «job не принят».
using JobId = uint64_t;
constexpr JobId kNoJob = 0;

// Поднимает очередь и задачу-воркер. Вызывать из setup() ДО
// http_server::install() и после vault::initialize().
//
// Мьютекс создаётся здесь, а не лениво: ленивая инициализация без защиты — гонка,
// когда HTTP и воркер впервые входят одновременно.
bool install();

// Заказывает provisioning. Пароль генерируется внутри модуля (формат —
// config::kMasterPasswordChars), потому что знать его должен только этот модуль и
// HTTP-слой, который его отдаст.
//
// Отказ, если хранилище уже provisioned: provisioning стирает раздел целиком, и
// такая ошибка — прямая потеря данных по неверному совету интерфейса.
//
// Возвращает 0, если воркер занят.
JobId submitProvision();

// Заказывает разблокировку. password копируется внутрь, вызывающая сторона вправе
// освободить свой буфер сразу.
//
// Возвращает 0, если воркер занят или идёт блокировка по неудачным попыткам.
JobId submitUnlock(const char* password);

// Заказывает полное уничтожение хранилища. Пароль не нужен и не передаётся:
// reset — единственная операция vault, которая работает на заблокированном
// хранилище, и именно поэтому она нужна при забытом мастер-пароле.
//
// ВНИМАНИЕ: операция необратима. Согласие пользователя проверяет HTTP-слой
// (подтверждение в теле запроса).
//
// Возвращает 0, если воркер занят. Если хранилище не provisioned, 0 НЕ
// возвращается — job принимается, а его poll() вернёт Refused: HTTP обязан
// отличать «занято, повтори» (503) от «нечего стирать» (409), и подменять одно
// другим значило бы врать пользователю о состоянии устройства.
JobId submitReset();

// Опрос job'а. false — такого job'а нет или он уже заменён следующим.
// Вызывающий обязан проверять kind: после завершения job'а слот переиспользуется.
bool poll(JobId jobId, JobView* out);

// Состояние для GET /api/auth/state.
State state();

// Генерирует мастер-пароль в out. Возвращает записанную длину без нуль-байта.
//
// Отдельная публичная функция, а не деталь внутри provisioning, потому что
// формат пароля — это контракт для пользователя, а не деталь реализации: его
// должен проверять selftest. Через submitProvision() это невозможно, там на
// provisioned-хранилище приходит Refused, то есть ровно один образец за прогон.
//
// out обязан быть не меньше config::kMasterPasswordChars + 1 байт.
size_t generateMasterPassword(char* out, size_t outLen);

// Подменяет источник случайности для selftest. Пока задан, randomWordIndex() и
// randomDigit() читают из bytes циклически вместо esp_fill_random(). Передать
// nullptr, чтобы вернуть настоящий источник.
//
// Смысл не в том, чтобы ускорить гейт, а в том, чтобы проверить смещение
// детерминированно. Статистикой распределение не поймать: при 4096 словах
// chi-square на 2000 выборках то и дело провалится из-за шума, а гейт, который
// иногда падает сам по себе, перестают читать. Через хук проверяются крайние
// значения напрямую: 0xFFFFFFFF обязан дать слово 4095, 0x00000000 — слово 0, а
// 250 и 251 обязаны быть отбракованы как цифры.
void setRandomSourceForTest(const uint8_t* bytes, size_t len);

// Копирует текущий токен сессии в out как 64 hex-символа с нуль-байтом.
// out обязан быть не меньше kSessionTokenHexLen + 1 байт. false — сессии нет.
bool sessionTokenHex(char* out, size_t outLen);

// Проверка токена сессии из заголовка X-PM-Session. tokenHex — ровно
// kSessionTokenHexLen символов. Сравнение постоянного времени: токен — секрет, и
// побайтовое сравнение превращается в oracle по времени.
bool sessionValid(const char* tokenHex, size_t len);

// Закрывает сессию: wipe токена, vault::close(). Хранилище на флеше цело.
// Вызывается по явному запросу пользователя и по простою.
bool lock();

// Досрочно закрывает сессию по таймауту простоя. Для selftest: без этого
// проверку kSessionTtlMs пришлось бы ждать 15 минут. В обычном пути вызывается
// воркером из цикла ожидания очереди.
void expireIdleSession(uint32_t ttlMs);

// Досрочно снимает блокировку по неудачным попыткам. Для selftest: иначе
// проверку пришлось бы ждать kAuthLockoutMs. В обычном пути блокировка
// снимается сама по истечении времени.
void clearLockout();

}  // namespace auth
}  // namespace pm
