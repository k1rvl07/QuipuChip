// Гейты стадии 4a: проверка crypto и хранилища на реальном железе.
// Полный прогон занимает около 300 секунд.
//
// Гейты 4a, каждый обязан печатать PASS или FAIL:
//   1. PBKDF2-HMAC-SHA256 по векторам RFC 7914 (корректность реализации).
//   2. Неверный пароль не меняет ни одного байта на флеше.
//   3. Подмена байта в заголовке и в шифротексте записи ломает аутентификацию.
//   3b. Оборванный заголовок (записан без маркера завершения) приводит к откату
//       на резервный слот, а не к отказу. Это проверка обрыва питания во время
//       сохранения: потерять из-за неё собственные пароли нельзя.
//   4. Round-trip: provisioning, запись, load(), перезагрузка-эквивалент.
//   5. Инварианты ёмкости: предельная запись, лимит счётчика, байтовый бюджет.
//   6. 480 сохранений с последующей сверкой содержимого и замером износа.
//   7. Компакция срабатывает по росту журнала и не теряет ни одной записи.
//
// Гейт 4b (устройство) и gate C (4c) здесь не проверяются.
//
// Запускается один раз из setup().
//
// wipeVault решает, что делать с непустым разделом vault. Гейты 2-6 работают
// поверх существующих данных, поэтому по умолчанию непустой раздел означает
// отказ: запуск по GPIO0 не должен молча снести настоящее хранилище.
//
// Wipe нужен для dev-цикла. Без него гейты нельзя прогнать второй раз: erase
// раздела заканчивается ребетом платы, selftest стартует на этом ребете и сам
// заводит хранилище, а следующая прошивка снова ребетит плату — и гейты видят
// непустой раздел, то есть каждый прогон после первого упирается в отказ.
// Поэтому режим, включённый флагом сборки, стирает раздел сам.
void run(bool wipeVault);

// Отдельные точки входа, чтобы гейты можно было прогнать по одной.
void cryptoGates();
void vaultGates();

