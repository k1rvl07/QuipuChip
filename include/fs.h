#pragma once

#include <FS.h>

#include <stddef.h>
#include <stdint.h>

#include "config.h"

// Владелец постоянного mount'а раздела web.
//
// Зачем отдельный модуль вместо кода прямо в selftest и http_server:
// LittleFS в arduino-esp32 2.0.17 — глобальный СИНГЛТОН
// (libraries/LittleFS/src/LittleFS.h): поля partitionLabel_ и _impl->mountpoint
// у него единственные, а end() снимает mount с того раздела, который был
// смонтирован последним begin(). Селftest монтировал web и сразу звал end()
// (src/selftest.cpp) — под живым HTTP-сервером это вырвало бы раздел из-под
// обработчиков запросов. Здесь web поднимается один раз и живёт до stop().
//
// Формат образа задаёт не этот модуль, а сборка: mklittlefs из data/ (page 256,
// block 4096) в раздел web. См. scripts/build_webfs.py.
namespace pm {
namespace fs {

// Открытый файл раздела web. Копируется свободно: File внутри FileImplPtr — это
// shared_ptr, так что копия делит один и тот же дескриптор с оригиналом.
struct WebFile {
  File handle;
  size_t size;
  // Нормализованное имя файла без ведущего слэша ("index.html"). Нужно не для
  // VFS, а вызывающему: Content-Type определяется по расширению, а для "/"
  // и "" расширения в запросе нет — только в разобранном здесь пути. Без этого
  // корень отдавался бы как application/octet-stream. Размер — как у пути,
  // обрезать нельзя: имя ассета вполне может быть длиннее 32 байт.
  char name[config::kWebPathMax];
};

// Монтирует web. formatOnFail здесь и всегда будет false: автоформат стёр бы
// залитый образ, и устройство молча отдавало бы 404 на каждом запросе.
// Повторный вызов, когда web уже смонтирован, успешен и ничего не делает.
bool mountWeb();
bool webMounted();

size_t webTotalBytes();
size_t webUsedBytes();

// Открывает файл на чтение. relPath — путь ОТНОСИТЕЛЬНО корня web, без ведущего
// слэша: "index.html", "app.js". Пустой путь и "/" означают index.html.
//
// Путь нормализуется и проверяется ДО склейки с базой раздела: начальные
// слэши и сегменты "." срезаются, а сегмент "..", управляющие байты и
// непечатаемый мусор приводят к отказу. Проверка своя, а не надейся на VFS:
// VFS разруливает ".." уже после склейки и вернёт размытый ENOENT на чём-то
// неожиданном, из-за чего обход легко не заметить.
bool openWeb(const char* relPath, WebFile& out);

// Сколько байт прочитано; 0 означает конец файла или ошибку. Специального кода
// ошибки здесь намеренно нет: частично прочитанный статический файл и обрыв
// отдавать одинаково бессмысленно, httpd в обоих случаях рвёт ответ.
size_t readWeb(WebFile& f, uint8_t* buf, size_t len);

void closeWeb(WebFile& f);

// Размер index.html, если он есть. Диагностика сборки образа: после прошивки
// без uploadfs это единственный способ отличить "раздел пуст" от "монтируется,
// но контента нет".
bool webIndexSize(size_t& sizeOut);

void stop();

}  // namespace fs
}  // namespace pm
